ARTIFACT_STORAGE_GUIDE = """
<persistent_storage_for_artifacts>
يمكن للقطع الأثرية تخزين واسترجاع البيانات عبر جلسات باستخدام window.storage:

**API:**
- await window.storage.get(key, shared?)       → {key, value, shared} | null
- await window.storage.set(key, value, shared?) → {key, value, shared} | null
- await window.storage.delete(key, shared?)     → {key, deleted, shared} | null
- await window.storage.list(prefix?, shared?)   → {keys, prefix?, shared} | null

**نمط المفاتيح:** استخدم مفاتيح هرمية تحت 200 حرف: "table:record_id"
- لا مسافات أو شرطات مائلة أو اقتباسات في المفاتيح
- ادمج البيانات المترابطة في مفتاح واحد لتجنب الاستدعاءات المتعاقبة

**النطاق:**
- personal (shared=false): يصل إليها المستخدم الحالي فقط
- shared (shared=true): يصل إليها جميع مستخدمي القطعة الأثرية

دائماً استخدم try-catch. المفاتيح غير الموجودة ترمي خطأً وليس null.
</persistent_storage_for_artifacts>
"""

